create table if not exists public.security_audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  actor_role text,
  action text not null,
  entity_type text not null,
  entity_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists security_audit_logs_created_at_idx
  on public.security_audit_logs (created_at desc);

create index if not exists security_audit_logs_entity_idx
  on public.security_audit_logs (entity_type, entity_id);

alter table public.security_audit_logs enable row level security;

drop policy if exists "Authenticated users can create audit logs"
  on public.security_audit_logs;

create policy "Authenticated users can create audit logs"
  on public.security_audit_logs
  for insert
  to authenticated
  with check (actor_user_id = auth.uid());

drop policy if exists "Admins can view audit logs"
  on public.security_audit_logs;

create policy "Admins can view audit logs"
  on public.security_audit_logs
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.profiles
      where public.profiles.id = auth.uid()
        and public.profiles.role = 'admin'
    )
  );
