create table if not exists public.finance_principal_adjustments (
  id bigint generated by default as identity primary key,
  finance_record_id bigint not null references public.finance_records(id) on delete cascade,
  adjustment_date date not null,
  adjustment_type text not null check (adjustment_type in ('increase', 'decrease')),
  adjustment_amount numeric not null check (adjustment_amount > 0),
  principal_before numeric not null,
  principal_after numeric not null,
  reason text not null check (length(trim(reason)) > 0),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.finance_principal_adjustments enable row level security;
revoke all on public.finance_principal_adjustments from anon, authenticated;
grant select on public.finance_principal_adjustments to authenticated;

drop policy if exists "Admins can view principal adjustments"
  on public.finance_principal_adjustments;
create policy "Admins can view principal adjustments"
  on public.finance_principal_adjustments
  for select to authenticated
  using (
    exists (
      select 1 from public.profiles
      where profiles.id = auth.uid()
        and lower(trim(coalesce(profiles.role, ''))) = 'admin'
    )
  );

create or replace function public.apply_interest_only_payment(
  p_user_id uuid,
  p_finance_record_id bigint,
  p_payment_amount numeric,
  p_payment_date date
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  finance_row public.finance_records%rowtype;
  payment_id public.finance_payments.id%type;
  principal_balance numeric;
  rate numeric;
  accrued_interest numeric;
  interest_balance numeric;
  interest_after numeric;
  balance_before numeric;
  balance_after numeric;
  elapsed_days integer;
  last_interest_date date;
begin
  if p_user_id is null then
    raise exception 'Login session not found';
  end if;

  if p_payment_amount is null or p_payment_amount <= 0 then
    raise exception 'Payment amount must be greater than zero';
  end if;

  if p_payment_date is null then
    raise exception 'Payment date is required';
  end if;

  select * into finance_row
  from public.finance_records
  where id = p_finance_record_id
    and lower(trim(coalesce(finance_type, ''))) = 'interest_only'
  for update;

  if not found then
    raise exception 'Interest-Only finance record not found';
  end if;

  if lower(trim(coalesce(finance_row.loan_status, ''))) not in ('active', '') then
    raise exception 'Interest-Only loan is already closed';
  end if;

  principal_balance := greatest(coalesce(
    finance_row.principal_outstanding,
    finance_row.original_principal,
    finance_row.principal_amount,
    0
  ), 0);
  rate := greatest(coalesce(finance_row.interest_rate, 0), 0);
  last_interest_date := coalesce(finance_row.last_interest_date, finance_row.entry_date, p_payment_date);

  if p_payment_date < last_interest_date then
    raise exception 'Payment date cannot be earlier than the last interest date';
  end if;

  elapsed_days := p_payment_date - last_interest_date;
  accrued_interest := round(principal_balance * rate * elapsed_days / 3000, 2);
  interest_balance := greatest(coalesce(finance_row.interest_due, 0), 0) + accrued_interest;

  if p_payment_amount > interest_balance then
    raise exception 'Interest payment cannot exceed accrued interest due: %', interest_balance;
  end if;

  balance_before := principal_balance + interest_balance;
  interest_after := interest_balance - p_payment_amount;
  balance_after := principal_balance + interest_after;

  insert into public.finance_payments (
    user_id,
    finance_record_id,
    payment_amount,
    payment_date,
    balance_before,
    balance_after,
    interest_payment,
    principal_payment
  ) values (
    p_user_id,
    p_finance_record_id,
    p_payment_amount,
    p_payment_date,
    balance_before,
    balance_after,
    p_payment_amount,
    0
  ) returning id into payment_id;

  update public.finance_records
  set amount = coalesce(amount, principal_balance),
      paid = coalesce(paid, 0) + p_payment_amount,
      pending = balance_after,
      interest_accrual = coalesce(interest_accrual, 0) + accrued_interest,
      interest_due = interest_after,
      interest_paid = coalesce(interest_paid, 0) + p_payment_amount,
      principal_outstanding = principal_balance,
      last_interest_date = p_payment_date,
      next_due_date = case
        when balance_after <= 0 or principal_balance <= 0 then null
        else p_payment_date + 30
      end,
      loan_status = case when balance_after <= 0 then 'closed' else 'active' end
  where id = p_finance_record_id;

  return jsonb_build_object(
    'payment_id', payment_id,
    'finance_record_id', p_finance_record_id,
    'payment_amount', p_payment_amount,
    'payment_date', p_payment_date,
    'interest_accrued', accrued_interest,
    'interest_payment', p_payment_amount,
    'principal_payment', 0,
    'principal_outstanding', principal_balance,
    'balance_before', balance_before,
    'balance_after', balance_after
  );
end;
$$;

create or replace function public.adjust_interest_only_principal(
  p_finance_record_id bigint,
  p_adjustment_date date,
  p_adjustment_type text,
  p_adjustment_amount numeric,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  finance_row public.finance_records%rowtype;
  profile_role text;
  principal_before numeric;
  principal_after numeric;
  interest_due_after numeric;
  accrued_interest numeric;
  rate numeric;
  elapsed_days integer;
  last_interest_date date;
  balance_before numeric;
  balance_after numeric;
  adjustment_id bigint;
  normalized_type text := lower(trim(coalesce(p_adjustment_type, '')));
begin
  select lower(trim(coalesce(role, '')))
  into profile_role
  from public.profiles
  where id = auth.uid();

  if coalesce(profile_role, '') <> 'admin' then
    raise exception 'Admin access is required to adjust principal';
  end if;

  if normalized_type not in ('increase', 'decrease') then
    raise exception 'Choose whether to increase or decrease principal';
  end if;

  if p_adjustment_amount is null or p_adjustment_amount <= 0 then
    raise exception 'Adjustment amount must be greater than zero';
  end if;

  if p_adjustment_date is null then
    raise exception 'Adjustment date is required';
  end if;

  if nullif(trim(coalesce(p_reason, '')), '') is null then
    raise exception 'Adjustment reason is required';
  end if;

  select * into finance_row
  from public.finance_records
  where id = p_finance_record_id
    and lower(trim(coalesce(finance_type, ''))) = 'interest_only'
  for update;

  if not found then
    raise exception 'Interest-Only finance record not found';
  end if;

  if lower(trim(coalesce(finance_row.loan_status, ''))) not in ('active', '') then
    raise exception 'Closed Interest-Only loans cannot be adjusted';
  end if;

  principal_before := greatest(coalesce(
    finance_row.principal_outstanding,
    finance_row.original_principal,
    finance_row.principal_amount,
    0
  ), 0);
  rate := greatest(coalesce(finance_row.interest_rate, 0), 0);
  last_interest_date := coalesce(finance_row.last_interest_date, finance_row.entry_date, p_adjustment_date);

  if p_adjustment_date < last_interest_date then
    raise exception 'Adjustment date cannot be earlier than the last interest date';
  end if;

  elapsed_days := p_adjustment_date - last_interest_date;
  accrued_interest := round(principal_before * rate * elapsed_days / 3000, 2);
  interest_due_after := greatest(coalesce(finance_row.interest_due, 0), 0) + accrued_interest;

  if normalized_type = 'increase' then
    principal_after := principal_before + p_adjustment_amount;
  else
    if p_adjustment_amount > principal_before then
      raise exception 'Principal reduction cannot exceed principal outstanding: %', principal_before;
    end if;
    principal_after := principal_before - p_adjustment_amount;
  end if;

  balance_before := principal_before + interest_due_after;
  balance_after := principal_after + interest_due_after;

  insert into public.finance_principal_adjustments (
    finance_record_id,
    adjustment_date,
    adjustment_type,
    adjustment_amount,
    principal_before,
    principal_after,
    reason,
    created_by
  ) values (
    p_finance_record_id,
    p_adjustment_date,
    normalized_type,
    p_adjustment_amount,
    principal_before,
    principal_after,
    trim(p_reason),
    auth.uid()
  ) returning id into adjustment_id;

  update public.finance_records
  set pending = balance_after,
      interest_accrual = coalesce(interest_accrual, 0) + accrued_interest,
      interest_due = interest_due_after,
      principal_outstanding = principal_after,
      last_interest_date = p_adjustment_date,
      next_due_date = case
        when balance_after <= 0 or principal_after <= 0 then null
        else p_adjustment_date + 30
      end,
      loan_status = case when balance_after <= 0 then 'closed' else 'active' end
  where id = p_finance_record_id;

  return jsonb_build_object(
    'adjustment_id', adjustment_id,
    'finance_record_id', p_finance_record_id,
    'adjustment_type', normalized_type,
    'adjustment_amount', p_adjustment_amount,
    'principal_before', principal_before,
    'principal_after', principal_after,
    'interest_accrued', accrued_interest,
    'balance_after', balance_after
  );
end;
$$;

revoke execute on function public.adjust_interest_only_principal(bigint, date, text, numeric, text)
  from public, anon;
grant execute on function public.adjust_interest_only_principal(bigint, date, text, numeric, text)
  to authenticated;